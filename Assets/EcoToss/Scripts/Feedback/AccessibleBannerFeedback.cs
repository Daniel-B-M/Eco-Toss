using System.Collections;
using EcoToss.Core;
using TMPro;
using UnityEngine;
using UnityEngine.UI;

namespace EcoToss.Feedback
{
    /// <summary>
    /// WCAG 2.2 Visual Accessibility Banner.
    /// Subscribes to GameEvents to display high-contrast textual feedback
    /// alongside audio and VFX cues (redundant sensory feedback for hearing impairments).
    /// </summary>
    public class AccessibleBannerFeedback : MonoBehaviour
    {
        #region Serialized Fields

        [Header("UI References")]
        [SerializeField] private GameObject bannerContainer;
        [SerializeField] private Image bannerBackground;
        [SerializeField] private TextMeshProUGUI bannerText;

        [Header("Display Timing")]
        [SerializeField, Min(0.5f)] private float outcomeDisplayDuration = 2.5f;

        [Header("WCAG 2.2 High-Contrast Palette (Ratio > 11:1)")]
        [SerializeField] private Color neutralInfoColor = new Color(0.10f, 0.14f, 0.22f, 0.94f);
        [SerializeField] private Color successColor = new Color(0.04f, 0.28f, 0.11f, 0.95f);
        [SerializeField] private Color failureColor = new Color(0.42f, 0.05f, 0.05f, 0.95f);
        [SerializeField] private Color textColor = Color.white;

        #endregion

        #region Private Fields

        private Coroutine _hideCoroutine;

        #endregion

        #region Unity Lifecycle

        // Generated by AI
        private void Awake()
        {
            if (bannerContainer != null)
            {
                bannerContainer.SetActive(false);
            }
        }

        // Generated by AI
        private void OnEnable()
        {
            GameEvents.WasteSpawned += HandleWasteSpawned;
            GameEvents.WasteSortedCorrectly += HandleWasteSortedCorrectly;
            GameEvents.WasteSortedIncorrectly += HandleWasteSortedIncorrectly;
            GameEvents.WasteMissed += HandleWasteMissed;
            GameEvents.GameStateChanged += HandleGameStateChanged;
        }

        // Generated by AI
        private void OnDisable()
        {
            GameEvents.WasteSpawned -= HandleWasteSpawned;
            GameEvents.WasteSortedCorrectly -= HandleWasteSortedCorrectly;
            GameEvents.WasteSortedIncorrectly -= HandleWasteSortedIncorrectly;
            GameEvents.WasteMissed -= HandleWasteMissed;
            GameEvents.GameStateChanged -= HandleGameStateChanged;
            StopHideRoutine();
        }

        #endregion

        #region Event Handlers

        // Generated by AI
        private void HandleWasteSpawned(WasteData wasteData)
        {
            if (wasteData == null) return;
            StopHideRoutine();

            string itemName = string.IsNullOrWhiteSpace(wasteData.DisplayName) ? "RESIDUO" : wasteData.DisplayName.ToUpper();
            string message = $"RESIDUO: {itemName}  |  CANECA: {FormatBinName(wasteData.CorrectBin)}";
            ShowBanner(message, neutralInfoColor);
        }

        // Generated by AI
        private void HandleWasteSortedCorrectly(WasteData wasteData)
        {
            string binName = wasteData != null ? FormatBinName(wasteData.CorrectBin) : "CANECA CORRECTA";
            string message = $"¡CORRECTO! CLASIFICADO EN CANECA {binName}";
            ShowBanner(message, successColor);
            ScheduleHide();
        }

        // Generated by AI
        private void HandleWasteSortedIncorrectly(WasteData wasteData, BinType wrongBinHit)
        {
            string expectedBin = wasteData != null ? FormatBinName(wasteData.CorrectBin) : "LA CANECA CORRECTA";
            string message = $"¡INCORRECTO! VA EN CANECA {expectedBin}";
            ShowBanner(message, failureColor);
            ScheduleHide();
        }

        // Generated by AI
        private void HandleWasteMissed(WasteData wasteData)
        {
            string expectedBin = wasteData != null ? FormatBinName(wasteData.CorrectBin) : "LA CANECA INDICADA";
            string message = $"¡FALLASTE EL TIRO! APUNTA A CANECA {expectedBin}";
            ShowBanner(message, failureColor);
            ScheduleHide();
        }

        private void HandleGameStateChanged(GameState newState)
        {
            if (newState != GameState.Playing && bannerContainer != null)
            {
                StopHideRoutine();
                bannerContainer.SetActive(false);
            }
        }

        #endregion

        #region UI Helpers

        private void ShowBanner(string message, Color backgroundColor)
        {
            if (bannerContainer == null || bannerText == null) return;

            bannerContainer.SetActive(true);
            bannerText.text = message;
            bannerText.color = textColor;

            if (bannerBackground != null)
            {
                bannerBackground.color = backgroundColor;
            }
        }

        private void ScheduleHide()
        {
            StopHideRoutine();
            _hideCoroutine = StartCoroutine(HideAfterDelayRoutine());
        }

        private void StopHideRoutine()
        {
            if (_hideCoroutine == null) return;
            StopCoroutine(_hideCoroutine);
            _hideCoroutine = null;
        }

        private IEnumerator HideAfterDelayRoutine()
        {
            yield return new WaitForSeconds(outcomeDisplayDuration);
            _hideCoroutine = null;
            if (bannerContainer != null)
            {
                bannerContainer.SetActive(false);
            }
        }

        private static string FormatBinName(BinType binType)
        {
            string raw = binType.ToString().ToLower();
            if (raw.Contains("white") || raw.Contains("recycl")) return "BLANCA (APROVECHABLES)";
            if (raw.Contains("green") || raw.Contains("organ")) return "VERDE (ORGÁNICOS)";
            if (raw.Contains("black") || raw.Contains("non")) return "NEGRA (NO APROVECHABLES)";
            return binType.ToString().ToUpper();
        }

        #endregion
    }
}